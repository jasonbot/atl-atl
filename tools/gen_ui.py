"""The 240 x 240 UI background: firmware/apps/APP/ui.png -> fw_ui.h.

One byte a pixel and a 256-colour RGB565 palette, like gen_logo.py. The app draws the bitmap once, then puts live
text over it. The SVG it came from is assets/ui.svg; rasterize it at 240 x 240 on black before running this.
"""
import argparse
import sys
from pathlib import Path

SIDE = 240
# The live icons in assets/ui.svg. These are cropped from the rendered background and drawn again at 100%, or
# faintly when their mode is off.
ICONS = (("REPEAT", (11, 145, 52, 180)), ("ONCE", (61, 145, 113, 180)),
         ("REC", (170, 145, 228, 162)), ("LATCH", (203, 7, 235, 38)), ("LINK", (131, 104, 170, 124)))


def rgb565(r, g, b):
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def rows(values, per_line, fmt):
    return ",\n".join("    " + ", ".join(fmt % v for v in values[i:i + per_line])
                      for i in range(0, len(values), per_line))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=Path)
    ap.add_argument("image", type=Path)
    ap.add_argument("--preview", type=Path)
    a = ap.parse_args()
    head = "/* generated by tools/gen_ui.py, do not edit */\n"
    if not a.image.exists():
        a.out.write_text(head + "#define FW_UI 0\n")
        print(f"ui: none ({a.image})")
        return 0
    from PIL import Image
    im = Image.open(a.image).convert("RGB")
    if im.size != (SIDE, SIDE):
        im = im.resize((SIDE, SIDE), Image.Resampling.LANCZOS)
    q = im.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:256 * 3]
    pal += [0] * (256 * 3 - len(pal))
    px = list(q.tobytes())
    text = head + "#define FW_UI 1\n"
    text += f"#define FW_UI_W {SIDE}u\n#define FW_UI_H {SIDE}u\n"
    text += f"static const uint16_t FW_UI_PAL[256] = {{\n{rows([rgb565(*pal[i * 3:i * 3 + 3]) for i in range(256)], 12, '0x%04X')}\n}};\n"
    text += f"static const uint8_t FW_UI_PX[{len(px)}] = {{\n{rows(px, 24, '%d')}\n}};\n"
    for name, (x0, y0, x1, y1) in ICONS:
        crop = im.crop((x0, y0, x1, y1))
        icon = []
        for y in range(y1 - y0):
            for x in range(x1 - x0):
                r, g, b = crop.getpixel((x, y))
                icon.append(rgb565(r, g, b) if max(r, g, b) > 4 else 0)
        text += (f"#define FW_UI_{name}_X {x0}u\n#define FW_UI_{name}_Y {y0}u\n"
                 f"#define FW_UI_{name}_W {x1 - x0}u\n#define FW_UI_{name}_H {y1 - y0}u\n"
                 f"static const uint16_t FW_UI_{name}[{len(icon)}] = {{\n{rows(icon, 12, '0x%04X')}\n}};\n")
    a.out.write_text(text)
    if a.preview:
        q.convert("RGB").save(a.preview)
    print(f"ui: {a.image.name} -> {SIDE} x {SIDE}, 256 colours, {len(px) + 512} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
