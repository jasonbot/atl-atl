"""The 240 x 240 UI background and its live slices: ui.png + ui_on.png + ui.json -> fw_ui.h.

The base image is the at-rest screen. The on image has the active version of every toggle or indicator at exactly the
same coordinates. The JSON slices name every region: text boxes, toggles, and status lights. This tool stores the
base as a 256-colour index image and the active slices as RGB565 sprites, so the app can overlay one region without
redrawing the whole screen.
"""
import argparse
import json
import sys
from pathlib import Path

SIDE = 240
# slice name in the Aseprite JSON -> C name
SLICES = {
    "selected key text": "KEY",
    "autotune message": "AUTO",
    "sample length text": "SAMPLE_LEN",
    "sample computed note length": "SAMPLE_NOTE",
    "Slice 11": "SAMPLE_ROOT",
    "bpm text": "BPM",
    "bpm blink": "BPM_BLINK",
    "usb indicator": "USB",
    "battery indicator": "BATTERY",
    "fx toggle": "FX",
    "arp toggle": "ARP",
    "glo toggle indicator": "GLO",
    "rec indicator": "REC",
    "sample presence indicator": "SAMPLE_PRESENCE",
    "seq toggle": "SEQ",
    "play indicator": "PLAY",
    "Slice 15": "KNOB1",
    "Slice 16": "KNOB2",
    "Slice 17": "KNOB3",
    "Slice 18": "KNOB4",
}
# active slices copied from the on image
ON = {"FX", "ARP", "GLO", "REC", "SAMPLE_PRESENCE", "SEQ", "PLAY", "BPM_BLINK", "USB", "BATTERY"}


def rgb565(r, g, b):
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def rows(values, per_line, fmt):
    return ",\n".join("    " + ", ".join(fmt % v for v in values[i:i + per_line])
                      for i in range(0, len(values), per_line))


def bounds(slices):
    out = {}
    for s in slices:
        b = s["keys"][0]["bounds"]
        out[s["name"]] = (b["x"], b["y"], b["w"], b["h"])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=Path)
    ap.add_argument("image", type=Path)
    ap.add_argument("--on", type=Path)
    ap.add_argument("--slices", type=Path)
    ap.add_argument("--preview", type=Path)
    a = ap.parse_args()
    head = "/* generated by tools/gen_ui.py, do not edit */\n"
    if not a.image.exists():
        a.out.write_text(head + "#define FW_UI 0\n")
        print(f"ui: none ({a.image})")
        return 0
    from PIL import Image
    im = Image.open(a.image).convert("RGB")
    if im.size != (SIDE, SIDE):
        im = im.resize((SIDE, SIDE), Image.Resampling.LANCZOS)
    q = im.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:256 * 3]
    pal += [0] * (256 * 3 - len(pal))
    px = list(q.tobytes())
    text = head + "#define FW_UI 1\n"
    text += f"#define FW_UI_W {SIDE}u\n#define FW_UI_H {SIDE}u\n"
    text += f"static const uint16_t FW_UI_PAL[256] = {{\n{rows([rgb565(*pal[i * 3:i * 3 + 3]) for i in range(256)], 12, '0x%04X')}\n}};\n"
    text += f"static const uint8_t FW_UI_PX[{len(px)}] = {{\n{rows(px, 24, '%d')}\n}};\n"

    if a.slices:
        j = json.loads(a.slices.read_text())
        regs = bounds(j["meta"]["slices"])
        for name, cname in SLICES.items():
            if name not in regs:
                raise SystemExit(f"gen_ui: missing slice {name!r}")
            x, y, w, h = regs[name]
            text += (f"#define FW_UI_{cname}_X {x}u\n#define FW_UI_{cname}_Y {y}u\n"
                     f"#define FW_UI_{cname}_W {w}u\n#define FW_UI_{cname}_H {h}u\n")
        if a.on:
            on = Image.open(a.on).convert("RGB")
            if on.size != (SIDE, SIDE):
                raise SystemExit(f"gen_ui: on image is {on.size}, expected {(SIDE, SIDE)}")
            for name, cname in SLICES.items():
                if cname not in ON:
                    continue
                x, y, w, h = regs[name]
                crop = on.crop((x, y, x + w, y + h))
                vals = [rgb565(*crop.getpixel((cx, cy))) for cy in range(h) for cx in range(w)]
                text += (f"static const uint16_t FW_UI_ON_{cname}[{len(vals)}] = {{\n"
                         f"{rows(vals, 12, '0x%04X')}\n}};\n")

    a.out.write_text(text)
    if a.preview:
        q.convert("RGB").save(a.preview)
    print(f"ui: {a.image.name} -> {SIDE} x {SIDE}, 256 colours, {len(px) + 512} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
